/* ── Article pages (markup generated by scripts/blog/transform.mjs) ── */

function initArticle() {
  // nav.js prepends the site nav to <body>; the skip link must stay first
  const skip = document.querySelector('.ab-skip');
  if (skip) document.body.prepend(skip);

  // "On this page": a sticky rail on wide screens, collapsed by default on narrow ones
  const toc = document.querySelector('.ab-toc details');
  if (toc && !window.matchMedia('(min-width: 1200px)').matches) toc.open = false;

  const status = document.querySelector('.ab-share-status');
  const say = (msg) => { if (status) status.textContent = msg; };
  const share = document.querySelector('[data-ab-share]');
  const copy = document.querySelector('[data-ab-copy]');
  const url = copy?.dataset.url || window.location.href;
  if (share && typeof navigator.share === 'function') {
    share.hidden = false;
    share.addEventListener('click', () => {
      navigator.share({ title: document.querySelector('h1')?.textContent.trim() || document.title, url })
        .catch(() => { /* dismissed */ });
    });
  }
  copy?.addEventListener('click', async () => {
    say((await copyText(url)) ? 'Link copied.' : `Couldn't copy automatically — the link is ${url}`);
  });
}

async function copyText(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch { /* fall back */ }
  const ta = document.createElement('textarea');
  ta.value = text;
  ta.setAttribute('readonly', '');
  ta.style.cssText = 'position:fixed;top:0;left:0;opacity:0;';
  document.body.appendChild(ta);
  ta.select();
  let ok = false;
  try { ok = document.execCommand('copy'); } catch { ok = false; }
  ta.remove();
  return ok;
}

/* ── Blog index: search + topic filter over the build-time catalog ──
   Everything a visitor types is handled as text: it is only ever compared,
   written with textContent, or wrapped in <mark> elements built with the DOM
   API — never parsed as HTML. */

function initIndex() {
  const dataEl = document.getElementById('ab-catalog');
  const form = document.querySelector('.ab-filter');
  if (!dataEl || !form) return;
  let posts;
  try { posts = JSON.parse(dataEl.textContent); } catch { return; }
  const q = form.querySelector('#ab-q');
  const topic = form.querySelector('#ab-topic');
  const results = document.getElementById('ab-results');
  const listing = document.getElementById('ab-listing');
  const status = document.getElementById('ab-status');

  const params = new URLSearchParams(window.location.search);
  q.value = (params.get('q') || '').slice(0, 100);
  const wanted = params.get('topic') || '';
  topic.value = [...topic.options].some(o => o.value === wanted) ? wanted : '';

  const render = () => {
    const query = q.value.trim().slice(0, 100);
    const t = topic.value;
    if (!query && !t) {
      results.hidden = true;
      results.replaceChildren();
      listing.hidden = false;
      status.textContent = '';
      return;
    }
    const terms = query.toLowerCase().split(/\s+/).filter(Boolean);
    const matches = posts.filter(p => (!t || p.topic === t)
      && terms.every(w => `${p.title} ${p.description} ${p.topic}`.toLowerCase().includes(w)));
    const grid = el('div', 'ab-grid');
    for (const p of matches) grid.appendChild(card(p, terms));
    const clear = el('button', 'ab-btn', 'Clear search and filter');
    clear.type = 'button';
    clear.addEventListener('click', () => { q.value = ''; topic.value = ''; render(); syncUrl(); q.focus(); });
    const children = [];
    if (!matches.length) children.push(el('p', 'ab-empty', 'No articles match. Try fewer or different words, or another topic.'));
    children.push(grid, clear);
    results.replaceChildren(...children);
    results.hidden = false;
    listing.hidden = true;
    const n = matches.length;
    status.textContent = `${n} article${n === 1 ? '' : 's'}${query ? ` matching “${query}”` : ''}${t ? ` in ${t}` : ''}.`;
  };
  const syncUrl = () => {
    const next = new URLSearchParams();
    if (q.value.trim()) next.set('q', q.value.trim().slice(0, 100));
    if (topic.value) next.set('topic', topic.value);
    const qs = next.toString();
    window.history.replaceState(null, '', `${window.location.pathname}${qs ? `?${qs}` : ''}`);
  };
  let timer = null;
  q.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(render, 150); });
  topic.addEventListener('change', () => { render(); syncUrl(); });
  form.addEventListener('submit', (e) => { e.preventDefault(); render(); syncUrl(); });
  render();
}

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
}

/** Text with search terms wrapped in <mark>, built from text nodes only. */
function highlighted(text, terms) {
  const frag = document.createDocumentFragment();
  if (!terms.length) { frag.appendChild(document.createTextNode(text)); return frag; }
  const lower = text.toLowerCase();
  let i = 0;
  while (i < text.length) {
    let best = -1, len = 0;
    for (const t of terms) {
      const at = lower.indexOf(t, i);
      if (at !== -1 && (best === -1 || at < best || (at === best && t.length > len))) { best = at; len = t.length; }
    }
    if (best === -1) { frag.appendChild(document.createTextNode(text.slice(i))); break; }
    if (best > i) frag.appendChild(document.createTextNode(text.slice(i, best)));
    frag.appendChild(el('mark', null, text.slice(best, best + len)));
    i = best + len;
  }
  return frag;
}

function card(p, terms) {
  const a = el('article', 'ab-card');
  a.appendChild(el('p', 'ab-card-topic', p.topic));
  const h = el('h2', 'ab-card-title');
  const link = el('a');
  if (typeof p.url === 'string' && /^\/[a-z0-9-]+$/.test(p.url)) link.href = p.url;
  link.appendChild(highlighted(p.title, terms));
  h.appendChild(link);
  a.appendChild(h);
  const ex = el('p', 'ab-card-excerpt');
  ex.appendChild(highlighted(p.description, terms));
  a.appendChild(ex);
  const meta = el('p', 'ab-card-meta');
  const time = el('time', null, p.date);
  time.dateTime = p.published;
  meta.append(time, ` · ${p.minutes} min read`);
  a.appendChild(meta);
  return a;
}
